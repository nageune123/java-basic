public class Main {
    public static void main(String[] args) {
        
        int age = 25;
        int score = 80;

        System.out.println(age >= 20);
        System.out.println(score >= 90);
        System.out.println(age >= 20 && score >= 90);
        System.out.println(age >= 20 || score >= 90);
        System.out.println(!(score >= 90));
    }
}   